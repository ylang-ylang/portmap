"""Render legacy Dockerfile frontends from the cold-construction JSON recipes.

The render_* functions only transform recipe data; they never inspect Dockerfiles,
read source files, or execute dependency installation. Run this module from the
repository root to regenerate all three checked-in frontends. Package/download
implementations live exclusively in the declared setup scripts.
"""
import argparse
from collections.abc import Mapping, Sequence
import json
from pathlib import Path
import shlex
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tests.browser.real_node.image_builder import PROXY_ENV


INPUT_ROOT = '/tmp/portmap-image-inputs'


def _header(recipe_path: str) -> str:
    return ('# Generated by tests/browser/image_recipes.py; do not edit.\n'
            f'# Recipe: {recipe_path}\n'
            '# Test-only image; never used by Portmap packaging or deployment.')


def _environment(environment: Mapping[str, str]) -> str:
    values = {**environment, **PROXY_ENV}
    return 'ENV ' + ' '.join(f'{name}={json.dumps(value)}' for name, value in values.items())


def _metadata(recipe: Mapping) -> str:
    return '\n'.join((
        _environment(recipe['environment']),
        f"USER {recipe['user']}",
        f"WORKDIR {recipe['workdir']}",
        'ENTRYPOINT ' + json.dumps(recipe['entrypoint']),
        'CMD ' + json.dumps(recipe['command']),
    ))


def _setup(recipe: Mapping, steps: Sequence[Mapping]) -> str:
    lines = ['COPY ' + json.dumps([source, f'{INPUT_ROOT}/{destination}'])
             for source, destination in recipe['inputs'].items()]
    commands = [shlex.join(['sh', f"{INPUT_ROOT}/{step['script']}", *step['arguments']])
                for step in steps]
    commands.append(f'rm -rf {INPUT_ROOT}')
    lines.append('RUN ' + ' && \\\n    '.join(commands))
    return '\n'.join(lines)


def render_desktop(recipe: Mapping) -> str:
    """Keep the legacy base/fixture/target/browser-tools/browser stage interface."""
    base_environment = {name: value for name, value in recipe['environment'].items()
                        if name != 'MOZ_HEADLESS'}
    base = '\n'.join((
        f"FROM {recipe['base']} AS base",
        _environment(base_environment),
        f"USER {recipe['user']}",
        f"WORKDIR {recipe['workdir']}",
        'ENTRYPOINT ' + json.dumps(recipe['entrypoint']),
        _setup(recipe, recipe['steps'][:1]),
    ))
    fixture = '\n'.join((
        'FROM base AS fixture',
        'COPY src /app/src',
        'COPY tests/browser/fixture.py tests/browser/dns.py /app/tests/browser/',
    ))
    target = '\n'.join((
        'FROM base AS target',
        _setup(recipe, [{'script': 'browser-setup.sh', 'arguments': ['target']}]),
        'COPY tests/browser/fixture.py tests/browser/target.py tests/browser/managed_fixture.py /app/tests/browser/',
        'CMD ["python", "/app/tests/browser/target.py"]',
    ))
    tools = '\n'.join((
        'FROM base AS browser-tools',
        '# No current adapter, extension, or browser-test source in this toolchain.',
        _setup(recipe, recipe['steps'][1:]),
        _metadata(recipe),
    ))
    browser = '\n'.join((
        'FROM browser-tools AS browser',
        'COPY src /app/src',
        'COPY extension/firefox /app/extension/firefox',
        'COPY tools/build_firefox_extension.py /app/tools/build_firefox_extension.py',
        'COPY pyproject.toml /app/pyproject.toml',
        'COPY tests/browser /app/tests/browser',
    ))
    return '\n\n'.join((_header('tests/browser/desktop-image.json'), base,
                         fixture, target, tools, browser)) + '\n'


def render_android(recipe: Mapping) -> str:
    """Derive Android from the prepared desktop toolchain, never current source."""
    arguments = [f'ARG {name}={json.dumps(value)}'
                 for name, value in recipe['buildArguments'].items()]
    stage = '\n'.join((
        'ARG BROWSER_BASE',
        f"FROM {recipe['base']}",
        *arguments,
        _setup(recipe, recipe['steps']),
        _metadata(recipe),
    ))
    return '\n\n'.join((_header('tests/browser/android-image.json'), stage)) + '\n'


def render_runtime(recipe: Mapping) -> str:
    """The runtime frontend now uses the repository root as its build context."""
    stage = '\n'.join((
        f"FROM {recipe['base']}",
        _environment({}),
        _setup(recipe, recipe['steps']),
        _metadata(recipe),
    ))
    return '\n\n'.join((_header('tests/browser/real_node/runtime-image.json'), stage)) + '\n'


FRONTENDS = (
    ('tests/browser/Dockerfile', 'tests/browser/desktop-image.json', render_desktop),
    ('tests/browser/Android.Dockerfile', 'tests/browser/android-image.json', render_android),
    ('tests/browser/real_node/Runtime.Dockerfile', 'tests/browser/real_node/runtime-image.json', render_runtime),
)


def main() -> None:
    parser = argparse.ArgumentParser(description='Regenerate canonical test-image Dockerfiles.')
    parser.add_argument('--check', action='store_true', help='Fail on stale generated files without changing them.')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    stale = []
    for frontend_path, recipe_path, render in FRONTENDS:
        recipe = json.loads((root / recipe_path).read_text(encoding='utf-8'))
        path = root / frontend_path
        expected = render(recipe).encode('utf-8')
        if args.check:
            if path.is_symlink() or not path.is_file() or path.read_bytes() != expected:
                stale.append(frontend_path)
        else:
            path.write_bytes(expected)
    if stale:
        raise SystemExit('Stale generated Dockerfiles: ' + ', '.join(stale) +
                         '; run python3 tests/browser/image_recipes.py')


if __name__ == '__main__':
    main()
